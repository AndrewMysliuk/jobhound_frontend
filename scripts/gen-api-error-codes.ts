import { mkdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const frontendRoot = path.resolve(scriptDir, "..")
const coreRoot = process.env.JOBHOUND_CORE_DIR ?? path.resolve(frontendRoot, "../jobhound_core")
const registryPath = path.join(coreRoot, "internal/publicapi/schema/generated/api-error-registry.json")
const defaultOutDir = path.resolve(frontendRoot, "app/types/generated")

interface RegistryEntryJson {
  code: string
}

function outDirFromArgv(argv: string[]): string {
  const index = argv.indexOf("--out")

  if (index === -1) {
    return defaultOutDir
  }

  const value = argv[index + 1]

  if (!value) {
    throw new Error("gen-api-error-codes: --out requires a directory")
  }

  return path.resolve(value)
}

function toConstName(code: string): string {
  return code
    .split(/[._]/)
    .filter(Boolean)
    .map((part) => {
      const digits = part.match(/\d+$/)?.[0] ?? ""
      const letters = digits ? part.slice(0, -digits.length) : part

      if (!letters) {
        return part
      }

      return letters.charAt(0).toUpperCase() + letters.slice(1).toLowerCase() + digits
    })
    .join("")
}

function isNodeError(error: unknown): error is NodeJS.ErrnoException {
  return error instanceof Error && "code" in error
}

function isRegistryEntry(value: unknown): value is RegistryEntryJson {
  return typeof value === "object" && value !== null && typeof (value as { code?: unknown }).code === "string"
}

async function loadEntries(): Promise<RegistryEntryJson[]> {
  let raw: string

  try {
    raw = await readFile(registryPath, "utf8")
  } catch (error: unknown) {
    if (isNodeError(error) && error.code === "ENOENT") {
      throw new Error(`gen-api-error-codes: registry not found at ${registryPath}. Set JOBHOUND_CORE_DIR or place jobhound_core at ../jobhound_core.`)
    }

    throw error
  }

  const parsed: unknown = JSON.parse(raw)

  if (!Array.isArray(parsed) || parsed.length === 0 || !parsed.every(isRegistryEntry)) {
    throw new Error(`gen-api-error-codes: expected a non-empty array of { code: string } in ${registryPath}`)
  }

  return parsed
}

function renderTypeScript(entries: RegistryEntryJson[]): string {
  const codeLines = entries.map((entry) => `  ${toConstName(entry.code)}: "${entry.code}",`)

  return `// Code generated by scripts/gen-api-error-codes.ts. DO NOT EDIT.
// Source: jobhound_core/internal/publicapi/schema/generated/api-error-registry.json
// Codes are for behaviour branching only. User-facing text comes from the envelope's error.message.

export const API_ERROR_CODES = {
${codeLines.join("\n")}
} as const

export type KnownApiErrorCodeType = (typeof API_ERROR_CODES)[keyof typeof API_ERROR_CODES]
`
}

async function main(): Promise<void> {
  const outDir = outDirFromArgv(process.argv.slice(2))
  const entries = await loadEntries()

  await mkdir(outDir, { recursive: true })

  const tsPath = path.join(outDir, "apiErrorCodes.ts")
  await writeFile(tsPath, renderTypeScript(entries))

  console.log(`gen-api-error-codes: ${entries.length} codes → ${path.relative(frontendRoot, tsPath)}`)
}

void main()
